package main

import (
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"
)

const caddyfileHeader = `# 由 MacPanel 生成 — 请勿手工编辑
{
	admin localhost:2019
	auto_https {{AUTO_HTTPS}}
}
`

// caddyfilePath 面板掌管的 Caddyfile
func caddyfilePath() string { return filepath.Join(dataDir, "caddy", "Caddyfile") }

// brewCaddyfilePath brew 版 caddy 的默认配置(仅一行 import,指向面板配置)
func brewCaddyfilePath() string {
	return "/opt/homebrew/etc/Caddyfile"
}

func renderCaddyfile(c *Config) string {
	var b strings.Builder
	auto := "off"
	for _, s := range c.Sites {
		if s.Enabled && s.TLS != "none" {
			auto = "on" // 有 https 站点时允许 caddy 自动管理(内部 CA / 文件模式不受影响)
			break
		}
	}
	b.WriteString(strings.ReplaceAll(caddyfileHeader, "{{AUTO_HTTPS}}", auto))
	b.WriteString("\n")
	for _, s := range c.Sites {
		if !s.Enabled {
			continue
		}
		b.WriteString(s.Domain + " {\n")
		switch s.Type {
		case "proxy":
			b.WriteString("\treverse_proxy " + s.Target + "\n")
		case "static":
			b.WriteString("\troot * " + s.Target + "\n\tfile_server\n")
		}
		switch s.TLS {
		case "internal":
			b.WriteString("\ttls internal\n")
		case "files":
			b.WriteString("\ttls " + s.Cert + " " + s.Key + "\n")
		}
		b.WriteString("}\n\n")
	}
	return b.String()
}

// GET /api/sites
func (app *App) handleSiteList(w http.ResponseWriter, r *http.Request, s *Session) {
	type siteView struct {
		Site
		CaddyInstalled bool `json:"caddy_installed"`
		CaddyRunning   bool `json:"caddy_running"`
	}
	installed := fileExists("/opt/homebrew/bin/caddy")
	running := false
	if out, code := runCmd(10*time.Second, "brew", "services", "list"); code == 0 {
		for _, line := range strings.Split(out, "\n") {
			f := strings.Fields(line)
			if len(f) >= 2 && f[0] == "caddy" {
				running = f[1] == "started"
			}
		}
	}
	out := []siteView{}
	app.store.Read(func(c *Config) {
		for _, s := range c.Sites {
			out = append(out, siteView{Site: s, CaddyInstalled: installed, CaddyRunning: running})
		}
	})
	apiOK(w, map[string]any{"sites": out, "caddy_installed": installed, "caddy_running": running})
}

// POST /api/sites {domain, type, target, tls, cert, key, enabled} — 新增或按 domain 更新
func (app *App) handleSiteSave(w http.ResponseWriter, r *http.Request, s *Session) {
	var req Site
	if err := readJSON(r, &req); err != nil {
		apiErr(w, 400, "参数错误")
		return
	}
	req.Domain = strings.TrimSpace(req.Domain)
	if req.Domain == "" || strings.ContainsAny(req.Domain, "{};\n\r") {
		apiErr(w, 400, "域名不合法")
		return
	}
	if req.Type != "proxy" && req.Type != "static" {
		apiErr(w, 400, "类型须为 proxy/static")
		return
	}
	if req.Type == "proxy" && (req.Target == "" || strings.ContainsAny(req.Target, "{};\n\r")) {
		apiErr(w, 400, "代理目标不合法")
		return
	}
	if req.Type == "static" && !dirExists(req.Target) {
		apiErr(w, 400, "静态目录不存在")
		return
	}
	switch req.TLS {
	case "none", "internal", "files", "":
	default:
		apiErr(w, 400, "TLS 模式不合法")
		return
	}
	if req.TLS == "files" && (!fileExists(req.Cert) || !fileExists(req.Key)) {
		apiErr(w, 400, "证书/私钥文件不存在")
		return
	}
	err := app.store.Update(func(c *Config) {
		replaced := false
		for i := range c.Sites {
			if c.Sites[i].Domain == req.Domain {
				c.Sites[i] = req
				replaced = true
			}
		}
		if !replaced {
			c.Sites = append(c.Sites, req)
		}
	})
	if err != nil {
		apiErr(w, 500, err.Error())
		return
	}
	app.audit("site_save", req.Domain)
	if msg, ok := app.syncCaddy(); !ok {
		apiErr(w, 500, "已保存,但 Caddy 同步失败: "+msg)
		return
	}
	apiOK(w, nil)
}

// POST /api/sites/delete {domain}
func (app *App) handleSiteDelete(w http.ResponseWriter, r *http.Request, s *Session) {
	var req struct {
		Domain string `json:"domain"`
	}
	if err := readJSON(r, &req); err != nil {
		apiErr(w, 400, "参数错误")
		return
	}
	_ = app.store.Update(func(c *Config) {
		out := c.Sites[:0]
		for _, s := range c.Sites {
			if s.Domain != req.Domain {
				out = append(out, s)
			}
		}
		c.Sites = out
	})
	app.audit("site_delete", req.Domain)
	if msg, ok := app.syncCaddy(); !ok {
		apiErr(w, 500, "已删除,但 Caddy 同步失败: "+msg)
		return
	}
	apiOK(w, nil)
}

// syncCaddy 生成 Caddyfile → 校验 → 若 caddy 在跑则热加载
func (app *App) syncCaddy() (string, bool) {
	_ = os.MkdirAll(filepath.Join(dataDir, "caddy"), 0o700)
	var content string
	app.store.Read(func(c *Config) { content = renderCaddyfile(c) })
	path := caddyfilePath()
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		return err.Error(), false
	}
	if !fileExists("/opt/homebrew/bin/caddy") {
		return "", true // 未装 caddy,仅保存
	}
	if out, code := runCmd(30*time.Second, "/opt/homebrew/bin/caddy", "validate", "--config", path); code != 0 {
		return strings.TrimSpace(out), false
	}
	// 同步到 brew 默认配置位置(一行 import),并热加载
	if fileExists(brewCaddyfilePath()) {
		importContent := "# generated by macpanel\nimport " + path + "\n"
		_ = os.WriteFile(brewCaddyfilePath(), []byte(importContent), 0o644)
	}
	_, _ = runCmd(30*time.Second, "/opt/homebrew/bin/caddy", "reload", "--config", brewCaddyfilePath())
	// reload 失败不阻塞保存(reload 通常因 caddy 未启动)
	return "", true
}

// POST /api/sites/caddy {action: install|start|stop|restart}
func (app *App) handleCaddyAction(w http.ResponseWriter, r *http.Request, s *Session) {
	var req struct {
		Action string `json:"action"`
	}
	if err := readJSON(r, &req); err != nil {
		apiErr(w, 400, "参数错误")
		return
	}
	switch req.Action {
	case "install":
		j := app.jobs.Start("brew install caddy", brewBin(), "install", "caddy")
		app.audit("caddy_install", "")
		apiOK(w, map[string]any{"job_id": j.ID})
		return
	case "start", "stop", "restart":
		out, code := runCmd(120*time.Second, brewBin(), "services", req.Action, "caddy")
		app.audit("caddy_"+req.Action, "")
		if code != 0 {
			apiErr(w, 500, strings.TrimSpace(out))
			return
		}
		apiOK(w, map[string]any{"output": strings.TrimSpace(out)})
		return
	default:
		apiErr(w, 400, "未知操作")
	}
}
